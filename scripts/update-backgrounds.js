const fs = require('fs');
const path = require('path');

const backgroundDir = path.join(__dirname, '../public/assets/backgrounds');
const outputFile = path.join(__dirname, '../public/js/background-list.js');

// Ensure assets directory exists
if (!fs.existsSync(backgroundDir)) {
  console.error(`Error: Directory not found: ${backgroundDir}`);
  process.exit(1);
}

// Helper to format display names and extract category
function parseFileInfo(filename) {
  const nameWithoutExt = path.parse(filename).name;
  const parts = nameWithoutExt.split('-');

  let category = 'other';
  let displayName = nameWithoutExt;

  if (parts.length >= 2) {
    category = parts[0];
    displayName = parts.slice(1).join(' ');
  }

  // Capitalize words
  displayName = displayName.replace(/\b\w/g, c => c.toUpperCase());
  category = category.replace(/\b\w/g, c => c.toUpperCase());

  return { category, displayName };
}

// Scan directory
const files = fs.readdirSync(backgroundDir).filter(file => {
  const ext = path.extname(file).toLowerCase();
  return ['.mp4', '.webm', '.mov'].includes(ext);
});

// Generate content
const backgroundList = files.map(file => {
  const { category, displayName } = parseFileInfo(file);
  return {
    filename: file,
    category: category,
    displayName: displayName
  };
});

const fileContent = `// Auto-generated by scripts/update-backgrounds.js
// Do not edit manually. Run 'node scripts/update-backgrounds.js' to update.

window.VIDEO_BACKGROUNDS = ${JSON.stringify(backgroundList, null, 2)};
`;

// Write file
fs.writeFileSync(outputFile, fileContent);

console.log(`✅ Generated background list with ${files.length} videos.`);
console.log(`📂 Output: ${outputFile}`);
